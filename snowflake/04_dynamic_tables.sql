-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT plan.ID AS ENTITY_ID, plan.NAME AS ENTITY_NAME,
       plan.REGION, plan.CATEGORY, plan.RISK_TIER, plan.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.PREMIUM_COUNT) AS PREMIUM_COUNT,
       SUM(observation.VALUE_PHP) AS VALUE_PHP,
       SUM(observation.CLAIM_COUNT) AS CLAIM_COUNT,
       SUM(observation.ESCALATED_COUNT) AS ESCALATED_COUNT,
       SUM(observation.SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(observation.REVIEW_DUE) AS REVIEW_DUE,
       SUM(observation.REVIEW_COMPLETED) AS REVIEW_COMPLETED,
       1000.0 * SUM(observation.CLAIM_COUNT) / NULLIF(SUM(observation.PREMIUM_COUNT), 0) AS CLAIMS_PER_1K,
       100.0 * SUM(observation.ESCALATED_COUNT) / NULLIF(SUM(observation.CLAIM_COUNT), 0) AS ESCALATION_SHARE_PCT,
       100.0 * SUM(observation.REVIEW_COMPLETED) / NULLIF(SUM(observation.REVIEW_DUE), 0) AS REVIEW_COMPLIANCE_PCT,
       AVG(observation.DOC_REJECT_PCT) AS AVG_DOC_REJECT_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.PLAN_DAILY observation
JOIN RAW.PLANS plan ON plan.ID = observation.ENTITY_ID
GROUP BY plan.ID, plan.NAME, plan.REGION, plan.CATEGORY, plan.RISK_TIER, plan.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(PREMIUM_COUNT) AS PREMIUM_COUNT, SUM(VALUE_PHP) AS VALUE_PHP,
       SUM(CLAIM_COUNT) AS CLAIM_COUNT, SUM(ESCALATED_COUNT) AS ESCALATED_COUNT,
       100.0 * SUM(ESCALATED_COUNT) / NULLIF(SUM(CLAIM_COUNT), 0) AS ESCALATION_SHARE_PCT
FROM RAW.PLAN_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.CLAIMS_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT CLAIM_CAUSE, SUM(CLAIM_COUNT) AS CLAIM_COUNT,
       SUM(ESCALATED_COUNT) AS ESCALATED_COUNT,
       SUM(SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(VALUE_PHP) AS EXPOSED_VALUE_PHP,
       100.0 * SUM(ESCALATED_COUNT) / NULLIF(SUM(CLAIM_COUNT), 0) AS ESCALATION_SHARE_PCT
FROM RAW.PLAN_DAILY
WHERE CLAIM_COUNT > 0
GROUP BY CLAIM_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(PREMIUM_COUNT) AS PREMIUMS, SUM(CLAIM_COUNT) AS CLAIMS,
         SUM(ESCALATED_COUNT) AS ESCALATED, SUM(SLA_BREACHED) AS BREACHES, SUM(VALUE_PHP) AS VALUE_PHP,
         SUM(REVIEW_DUE) AS REVIEW_DUE, SUM(REVIEW_COMPLETED) AS REVIEW_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.PLAN_DAILY
), book AS (SELECT COUNT(*) AS PLAN_COUNT FROM RAW.PLANS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.CLAIM_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Claims per 1,000 Premium Payments' AS TITLE,
         1000.0 * CLAIMS / NULLIF(PREMIUMS, 0) AS VALUE_NUM, '' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Claims Notified', CLAIMS, '' FROM observations
  UNION ALL SELECT 3, 'Escalated to Claims Investigation', ESCALATED, '' FROM observations
  UNION ALL SELECT 4, 'Escalation Rate', 100.0 * ESCALATED / NULLIF(CLAIMS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Settlement SLA Breaches', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'Premium Value (PHP M)', VALUE_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Premium Payments Received', PREMIUMS, '' FROM observations
  UNION ALL SELECT 8, 'Claims File Audit Compliance', 100.0 * REVIEW_COMPLETED / NULLIF(REVIEW_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Plans Monitored', PLAN_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Claim File Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Claim Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.CLAIMS_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
